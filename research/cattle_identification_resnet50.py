"""# RESNET50 - CNN BENCHMARK"""

import torch
import torch.nn as nn
from torchvision.models import resnet50
from torch.utils.data import DataLoader
from torch.optim.lr_scheduler import StepLR

# Define the device
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Device:- ", device)

# Define the model
class ResNet50(nn.Module):
    def __init__(self, num_classes):
        super(ResNet50, self).__init__()
        self.resnet = resnet50(pretrained=False)
        # Replace the final fully connected layer with custom classifier
        num_ftrs = self.resnet.fc.in_features
        self.resnet.fc = nn.Sequential(
            nn.Linear(num_ftrs, num_classes)
        )

    def forward(self, x):
        return self.resnet(x)

# Define the model
model = ResNet50(num_classes=num_classes).to(device)
model

"""## TRAINING"""

# Define the loss function
criterion = nn.CrossEntropyLoss()

# Define the optimizer
optimizer = optim.Adam(model.parameters())

# Define the learning rate scheduler
scheduler = StepLR(optimizer, step_size=5, gamma=0.1)

# Initialize lists to store metrics
losses = []
accuracies = []
precisions = []
recalls = []
f1_scores = []

# Train the model
num_epochs = 15
for epoch in range(num_epochs):
    model.train()
    running_loss = 0.0
    running_corrects = 0
    total_samples = 0
    all_preds = []
    all_labels = []

    for images, labels in tqdm(dataloader):
        images, labels = images.to(device), labels.to(device)
        optimizer.zero_grad()
        outputs = model(images)
        loss = criterion(outputs, labels)
        _, preds = torch.max(outputs, 1)
        running_corrects += torch.sum(preds == labels.data)
        total_samples += labels.size(0)
        loss.backward()
        optimizer.step()
        running_loss += loss.item() * images.size(0)
        all_preds.extend(preds.cpu().tolist())
        all_labels.extend(labels.cpu().tolist())

    epoch_loss = running_loss / len(dataset)
    epoch_accuracy = running_corrects.double() / total_samples
    precision = precision_score(all_labels, all_preds, average='macro')
    recall = recall_score(all_labels, all_preds, average='macro')
    f1 = f1_score(all_labels, all_preds, average='macro')

    # Append metrics to lists
    losses.append(epoch_loss)
    accuracies.append(epoch_accuracy.item())
    precisions.append(precision)
    recalls.append(recall)
    f1_scores.append(f1)

    print(f"Epoch [{epoch+1}/{num_epochs}], Loss: {epoch_loss:.4f}, Accuracy: {epoch_accuracy:.4f}, Precision: {precision:.4f}, Recall: {recall:.4f}, F1-score: {f1:.4f}")
    scheduler.step()

